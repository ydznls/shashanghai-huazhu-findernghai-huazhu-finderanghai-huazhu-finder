import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {extractOpening,extractMetro,selectHotels,normalizeHotel,validateDates} from '../lib/official.mjs';
import {BRAND_CATALOG,BRAND_CATEGORIES,matchBrand} from '../lib/brands.mjs';
const evidence=JSON.parse(await fs.readFile('data/brand-evidence.json','utf8'));
assert.equal(new Set(BRAND_CATALOG.map(b=>b.id)).size,BRAND_CATALOG.length);
assert.equal(new Set(BRAND_CATALOG.map(b=>b.name)).size,BRAND_CATALOG.length);
for(const b of evidence.all)assert(matchBrand(b.name),`Missing official brand ${b.name}`);
for(const b of evidence.groups)assert.equal(matchBrand(b.name)?.category,b.type,`Wrong category ${b.name}`);
for(const [name,expected] of [['上海宜必思尚品酒店','宜必思尚品'],['上海美仑国际酒店','美仑国际'],['上海美仑美奂酒店','美仑美奂'],['上海汉庭优佳酒店','汉庭优佳'],['上海汉庭快捷酒店','汉庭快捷'],['上海施柏阁大观酒店','施柏阁大观'],['上海全季大观酒店','全季大观'],['上海漫心府','漫心府'],['上海CitiGO HOUSE欢阁服务公寓','CitiGO HOUSE欢阁服务公寓'],['上海城家公寓酒店','城家公寓酒店']])assert.equal(matchBrand('',name)?.name,expected);
assert.equal(matchBrand('宜必思','上海宜必思尚品酒店')?.name,'宜必思尚品');
assert.equal(extractOpening('全季酒店成立于2010年，开业已超过1100家。'),null);
assert.equal(extractOpening('2024年装修'),null);
assert.equal(extractOpening('经济型 | 2023年开业 | 汉庭3.51').year,2023);
assert.equal(extractMetro('距市中心300米'),null);
assert.equal(extractMetro('肇嘉浜路1065号（距地铁1号线、9号线、11号线徐家汇站10号口367米，步行5分钟）').meters,367);
assert.equal(extractMetro('距离地铁11号线安亭站1号口100米正对面财富广场内').meters,100);
assert.equal(extractMetro('距离地铁江湾镇站1.5公里，步行20分钟').meters,1500);
const h=[{id:'a',name:'全季',score:4.9,metro:{meters:100},opening:null},{id:'b',name:'汉庭',score:4.5,metro:{meters:700},opening:{year:2024}}];
assert.deepEqual(selectHotels(h,{maxMetro:500,minScore:4.8}).map(x=>x.id),['a']);
assert.deepEqual(selectHotels(h,{minYear:2023}).map(x=>x.id),['b']);
assert.equal(selectHotels(h,{minYear:2023,includeUnknown:true}).length,2);
assert.throws(()=>validateDates('2026-02-30','2026-02-31'));
const snapshot=JSON.parse(await fs.readFile('data/official-snapshot.json','utf8'));
assert(snapshot.hotels.length>0);assert.equal(new Set(snapshot.hotels.map(h=>h.id)).size,snapshot.hotels.length);
for(const h of snapshot.hotels){assert.equal(h.city,'上海');assert.equal(new URL(h.sourceUrl).hostname,'m.huazhu.com');assert.equal(h.quote,null);assert(!/虚拟|测试|停业|歇业|酒店停$|质量整改/.test(h.name));}
for(const b of BRAND_CATALOG)assert(selectHotels(snapshot.hotels,{brand:b.name}).every(h=>h.brand===b.name));
for(const category of BRAND_CATEGORIES.filter(c=>c!=='全部品类'))assert(selectHotels(snapshot.hotels,{category}).every(h=>matchBrand(h.brand)?.category===category));
